-- =========================================
-- MUSIC PLAYER - SUPABASE SETUP GABUNGAN
-- =========================================

-- 1. BUAT TABEL TRACKS
CREATE TABLE IF NOT EXISTS public.tracks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    file_path text,
    created_at timestamptz DEFAULT now()
);

-- 2. TAMBAHKAN KOLOM SOUNDCLOUD
ALTER TABLE public.tracks
ADD COLUMN IF NOT EXISTS soundcloud_url text;

-- Izinkan file_path kosong untuk lagu SoundCloud
ALTER TABLE public.tracks
ALTER COLUMN file_path DROP NOT NULL;

-- 3. AKTIFKAN RLS
ALTER TABLE public.tracks ENABLE ROW LEVEL SECURITY;

-- 4. IZIN AKSES TABEL
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON public.tracks TO anon, authenticated;
GRANT INSERT, DELETE ON public.tracks TO authenticated;

-- 5. POLICY TABEL TRACKS
DROP POLICY IF EXISTS "Music Player Public Read" ON public.tracks;
CREATE POLICY "Music Player Public Read"
ON public.tracks
FOR SELECT
TO anon, authenticated
USING (true);

DROP POLICY IF EXISTS "Music Player Admin Insert" ON public.tracks;
CREATE POLICY "Music Player Admin Insert"
ON public.tracks
FOR INSERT
TO authenticated
WITH CHECK (true);

DROP POLICY IF EXISTS "Music Player Admin Delete" ON public.tracks;
CREATE POLICY "Music Player Admin Delete"
ON public.tracks
FOR DELETE
TO authenticated
USING (true);

-- 6. BUAT STORAGE BUCKET MUSIC
INSERT INTO storage.buckets (id, name, public)
VALUES ('music', 'music', true)
ON CONFLICT (id)
DO UPDATE SET public = true;

-- 7. POLICY STORAGE
DROP POLICY IF EXISTS "Music Player Public Storage Read" ON storage.objects;
CREATE POLICY "Music Player Public Storage Read"
ON storage.objects
FOR SELECT
TO anon, authenticated
USING (bucket_id = 'music');

DROP POLICY IF EXISTS "Music Player Admin Storage Upload" ON storage.objects;
CREATE POLICY "Music Player Admin Storage Upload"
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (bucket_id = 'music');

DROP POLICY IF EXISTS "Music Player Admin Storage Delete" ON storage.objects;
CREATE POLICY "Music Player Admin Storage Delete"
ON storage.objects
FOR DELETE
TO authenticated
USING (bucket_id = 'music');

