-- Jalankan sekali di Supabase SQL Editor
create table if not exists public.tracks (
  id bigint generated by default as identity primary key,
  title text not null,
  file_path text not null,
  created_at timestamptz not null default now()
);

alter table public.tracks enable row level security;

-- Playlist bisa dibaca publik (halaman player)
drop policy if exists "Public can read tracks" on public.tracks;
create policy "Public can read tracks" on public.tracks
for select to anon, authenticated using (true);

-- Admin yang login dapat memasukkan/menghapus record
-- Batasi akun login dengan mematikan sign-up publik di Auth Settings.
drop policy if exists "Authenticated can insert tracks" on public.tracks;
create policy "Authenticated can insert tracks" on public.tracks
for insert to authenticated with check (true);

drop policy if exists "Authenticated can delete tracks" on public.tracks;
create policy "Authenticated can delete tracks" on public.tracks
for delete to authenticated using (true);

insert into storage.buckets (id,name,public)
values ('music','music',true)
on conflict (id) do update set public=true;

-- Public playback/read access for bucket music
drop policy if exists "Public can read music files" on storage.objects;
create policy "Public can read music files" on storage.objects
for select to anon, authenticated using (bucket_id='music');

-- Upload/delete from admin session
drop policy if exists "Authenticated can upload music" on storage.objects;
create policy "Authenticated can upload music" on storage.objects
for insert to authenticated with check (bucket_id='music');

drop policy if exists "Authenticated can delete music" on storage.objects;
create policy "Authenticated can delete music" on storage.objects
for delete to authenticated using (bucket_id='music');
